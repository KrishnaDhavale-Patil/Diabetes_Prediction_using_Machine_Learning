# --------------------------------------------------------------------------
# CACHED LOADERS
# --------------------------------------------------------------------------
@st.cache_resource
def artifacts_exist():
    required = ["scaler.pkl", "feature_names.pkl", "metrics.csv", "confusion_matrices.pkl"]
    required += list(MODEL_FILES.values())
    return all(os.path.exists(os.path.join(MODELS_DIR, f)) for f in required)


@st.cache_resource
def load_model(name):
    return joblib.load(os.path.join(MODELS_DIR, MODEL_FILES[name]))


@st.cache_resource
def load_scaler():
    return joblib.load(os.path.join(MODELS_DIR, "scaler.pkl"))


@st.cache_resource
def load_feature_names():
    return joblib.load(os.path.join(MODELS_DIR, "feature_names.pkl"))


@st.cache_data
def load_metrics():
    return pd.read_csv(os.path.join(MODELS_DIR, "metrics.csv"), index_col=0)


@st.cache_resource
def load_confusion_matrices():
    return joblib.load(os.path.join(MODELS_DIR, "confusion_matrices.pkl"))


@st.cache_data
def load_feature_importance():
    path = os.path.join(MODELS_DIR, "feature_importance.csv")
    if os.path.exists(path):
        return pd.read_csv(path, index_col=0)
    return None


